export function answerGeneralConsultation(question: string): string {
  if (/利率|收益|计息/.test(question)) return '执行利率和预计收益必须结合客户分类、产品期限与业务日有效利率查询。请选择客户后，我可以调用 Java 业务服务给出确定性结果。'
  if (/通知/.test(question)) return '单位通知存款强调流动性，需要按约定提前发出支取通知；具体期限、起存金额和执行利率应以业务服务查询结果为准。'
  if (/定期|长期/.test(question)) return '单位定期存款适合期限明确、短期内无需使用的资金。选择客户后可进一步校验准入、期限、最低起存金额和执行利率。'
  if (/意向|办理|开户/.test(question)) return '当前 AI 工作台最多创建办理意向，不会直接开户或执行资金交易；正式办理仍由确定性业务系统完成。'
  if (/产品|能办|有哪些/.test(question)) return '当前演示覆盖单位定期存款和单位通知存款等产品。客户可办理范围属于结构化业务事实，需要先选择客户后查询准入。'
  return '我可以介绍对公存款产品、期限、利率与办理意向规则。涉及具体客户的准入、执行利率和收益试算时，请先选择客户。'
}
